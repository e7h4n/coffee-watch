"""Generate native-size, grayscale-antialiased ASCII VLW fonts from OFL Noto Sans."""
from pathlib import Path
import struct
from PIL import Image, ImageDraw, ImageFont
root=Path(__file__).resolve().parents[1]
source=root/'assets/fonts/NotoSans.ttf'
sizes=[18,20,22,26,32,34,40,46,60,64,90]
parts=['// Generated by tools/make_fonts.py from OFL Noto Sans.\n#pragma once\n#include <cstdint>\n']
total=0
for size in sizes:
    font=ImageFont.truetype(str(source),size)
    axes=font.get_variation_axes()
    font.set_variation_by_axes([500 if a['name']==b'Weight' else a['default'] for a in axes])
    chars='Ready' if size==60 else '0123456789.:-' if size>=64 else ''.join(chr(i) for i in range(33,127))
    chars=''.join(sorted(set(chars)))
    records=[];pixels=[];ascent=descent=0
    for ch in chars:
        l,t,r,b=font.getbbox(ch,anchor='ls');w=r-l;h=b-t
        im=Image.new('L',(w,h));ImageDraw.Draw(im).text((-l,-t),ch,font=font,fill=255,anchor='ls')
        records.append((ord(ch),h,w,round(font.getlength(ch)),-t,l,0));pixels.append(im.tobytes())
        ascent=max(ascent,-t);descent=max(descent,b)
    data=struct.pack('>6i',len(chars),11,size,0,ascent,descent)
    data+=b''.join(struct.pack('>7i',*rec) for rec in records)+b''.join(pixels)
    parts.append(f'static const uint8_t font_{size}[]={{\n'+''.join(','.join(str(x) for x in data[i:i+32])+',\n' for i in range(0,len(data),32))+'};\n')
    total+=len(data)
parts.append('static const int font_sizes[]={'+','.join(map(str,sizes))+'};\n')
parts.append('static const uint8_t *const font_data[]={'+','.join('font_'+str(x) for x in sizes)+'};\n')
(root/'main/smooth_fonts.h').write_text(''.join(parts))
print('Font bytes:',total)
